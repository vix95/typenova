/** Types shared by the Globe renderer phases: node/edge records and the scene object that replaces the former closure. */
import { type SectionNode, type SectionGraphModel } from "../graph/section-model";
import { type GraphSection } from "./graph-state";

export type GraphNode = { s: GraphSection; key: string; lodRank: number; x: number; y: number; gx: number; gy: number; gz: number; depth: number; vx: number; vy: number; radius: number; color: string; dragging: boolean; suppressClick: boolean; el: SVGGElement | null };
export type GraphEdge = { a: GraphNode; b: GraphNode; kind: "tree" | "section" | "link"; el: SVGLineElement | null };
export interface GlobeScene {
  graph: HTMLElement;
  filter: string;
  visible: SectionNode[];
  total: number;
  status: HTMLElement;
  renderToken: number;
  viewportWidth: number;
  viewportHeight: number;
  ns: "http://www.w3.org/2000/svg";
  svg: SVGSVGElement;
  animateEntry: boolean;
  scene: SVGGElement;
  edgeLayer: SVGGElement;
  nodeLayer: SVGGElement;
  add: (tag: string, attrs: Record<string, string>, parent?: Element) => SVGElement;
  sphereRadius: number;
  palette: string[];
  hashFor: (value: string) => number;
  sectionsById: Map<string, SectionNode>;
  headingLevelColor: (hex: string, level: number, hueOffset?: number) => string;
  colorFor: (section: GraphSection) => string;
  blendNodeColors: (a: string, b: string) => string;
  nodes: GraphNode[];
  byId: Map<string, GraphNode>;
  sectionGraphModel: SectionGraphModel;
  saved: Record<string, { x: number; y: number }>;
  positionsKey: "typenova.brain.positions.v3";
  storedPositions: Record<string, unknown>;
  needsLayout: boolean;
  edgeList: GraphEdge[];
  edgeByPair: Map<string, GraphEdge>;
  nodeIndex: Map<GraphNode, number>;
  addEdge: (a: GraphNode, b: GraphNode, kind: "tree" | "section" | "link") => void;
  degree: Map<GraphNode, number>;
  lodEnabled: boolean;
  lodOrder: GraphNode[];
  lodZoomBase: number;
  initialLodBudget: number;
  lodBudget: number;
  lodTierSet: Set<GraphNode> | null;
  lodFullZoomFactor: number;
  baseGlobeStatusText: string;
  lodStatusText: string;
  nodeEls: Map<string, SVGGElement>;
  nodeTitle: (n: GraphNode) => string;
  hoveredGraphNode: GraphNode | null;
  edgesByNode: Map<GraphNode, GraphEdge[]>;
  emphasizedNodes: Set<GraphNode>;
  emphasizedEdges: Set<GraphEdge>;
  applyGraphEmphasis: () => void;
  relatedTooltipNode: GraphNode | null;
  dragEdgeUpdateFrame: number;
  scheduleDragEdgeUpdate: () => void;
  restoreRelatedTooltip: (node: GraphNode) => void;
  lodVisibleNodes: GraphNode[];
  lodVisibleEdges: GraphEdge[];
  nodeTitleForAria: (n: GraphNode) => string;
  ensureNodeElement: (n: GraphNode) => SVGGElement;
  ensureEdgeElement: (edge: GraphEdge) => SVGLineElement;
  isGraphNodeInLod: (node: GraphNode) => boolean;
  syncGlobeLodVisibility: () => void;
  updateGlobeLod: () => void;
  updateEdges: () => void;
  projectNodeGlobe: (n: GraphNode) => void;
  projectGlobe: () => void;
  savePositions: () => void;
  updateLabelScale: () => void;
  labelLayoutTimer: number | undefined;
  scheduleLabelScaleUpdate: () => void;
  applyView: () => void;
  fit: () => void;
  panStart: { x: number; y: number; px: number; py: number; pointerId: number; moved: boolean; canDeselect: boolean } | null;
  globeInteractionFrame: number;
  lastGlobeInteractionDraw: number;
  drawGlobeInteraction: (time: number) => void;
  endPan: (event: Event) => void;
  forceX: Float64Array<ArrayBuffer>;
  forceY: Float64Array<ArrayBuffer>;
  cellX: Int32Array<ArrayBuffer>;
  cellY: Int32Array<ArrayBuffer>;
  spatialBuckets: Map<string, number[]>;
  reusableSpatialBuckets: number[][];
  tick: (time?: number, floating?: boolean, elapsedMs?: number) => void;
  drawPositions: () => void;
  zoom: (factor: number) => void;
  startAmbientMotion: () => void;
  enableAmbientAfterLayout: () => void;
}
